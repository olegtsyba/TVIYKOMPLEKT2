// Значення enum з внутрішніми подвійними лапками (наприклад 'заперечення "Подумаю"')
// модель іноді віддає без екранування — це ламає JSON. Для схеми, яку бачить API,
// внутрішні " замінюємо на ' (без конфлікту з обгорткою рядка), а після парсингу
// мапимо назад на канонічну назву з REASONS.
const SCHEMA_REASONS = REASONS.map((r) => r.replace(/"/g, "'"));

const RESPONSE_SCHEMA = {
  type: 'object',
  properties: {
    reason: { type: 'string', enum: SCHEMA_REASONS },
    confidence: { type: 'string', enum: ['high', 'medium', 'low'] },
    rationale: { type: 'string' },
  },
  required: ['reason', 'confidence', 'rationale'],
  additionalProperties: false,
};

function toCanonicalReason(schemaReason) {
  const idx = SCHEMA_REASONS.indexOf(schemaReason);
  return idx >= 0 ? REASONS[idx] : schemaReason;
}

async function classifyDialog(client, dialog) {
  const prompt = PROMPT_TEMPLATE.replace('{dialog_text}', dialog.rawText || '(порожня переписка)');

  const response = await client.messages.create({
    model: MODEL,
    max_tokens: 4096,
    output_config: {
      format: { type: 'json_schema', schema: RESPONSE_SCHEMA },
    },
    messages: [{ role: 'user', content: prompt }],
  });

  const textBlock = response.content.find((b) => b.type === 'text');
  if (!textBlock) throw new Error('Відповідь моделі не містить текстового блоку.');
  const parsed = JSON.parse(textBlock.text);
  return { ...parsed, reason: toCanonicalReason(parsed.reason) };
}

async function main() {
  if (!process.env.ANTHROPIC_API_KEY) {
    console.error(
      'Помилка: ANTHROPIC_API_KEY не задано у файлі .env.\n' +
      'Додай ключ у .env перед запуском (див. .env.example).'
    );
    process.exit(1);
  }

  if (!fs.existsSync(config.OUTPUT_PATH)) {
    console.error(
      `Файл із зібраними діалогами не знайдено: ${config.OUTPUT_PATH}\n` +
      `Спочатку виконай: npm run collect`
    );
    process.exit(1);
  }

  const dialogs = JSON.parse(fs.readFileSync(config.OUTPUT_PATH, 'utf-8'));
  console.log(`Завантажено діалогів для класифікації: ${dialogs.length}`);

  // Відновлення після часткового збою (наприклад, вичерпання кредитів API
  // посеред прогону): якщо для того самого leadId (стабільний ID картки в
  // KeyCRM, не позиція в колонці) уже є успішний результат (reason не null)
  // у поточному CLASSIFICATION_OUTPUT_PATH — не витрачаємо кредити повторно,
  // переносимо його як є.
  //
  // КЛЮЧОВО: раніше кеш був keyed за cardIndex (позицією картки в DOM на
  // момент збору). Це ламалось, щойно LIVE-прогін реально видаляв картки з
  // колонки — позиції зсувались, і нова картка на старій позиції помилково
  // "успадковувала" чужу стару класифікацію, ніколи не потрапляючи на
  // реальний розгляд. leadId — стабільний ID ліда з KeyCRM (data-id картки /
  // той самий ID, що в /leads/{id}) — не змінюється, поки картка не
  // видалена, тож коректно відрізняє "цю саму картку знову" від "нового
  // ліда, що просто зайняв стару позицію".
  let resumedById = new Map();
  if (fs.existsSync(config.CLASSIFICATION_OUTPUT_PATH)) {
    try {
      const prev = JSON.parse(fs.readFileSync(config.CLASSIFICATION_OUTPUT_PATH, 'utf-8'));
      resumedById = new Map(prev.filter((r) => r.reason && r.leadId).map((r) => [r.leadId, r]));
      if (resumedById.size) {
        console.log(`Знайдено ${resumedById.size} вже успішно класифікованих карток у попередньому результаті (за leadId) — пропускаю їх.`);
      }
      const legacyCount = prev.filter((r) => r.reason && !r.leadId).length;
      if (legacyCount) {
        console.log(`${legacyCount} записів у попередньому результаті без leadId (старий формат кешу) — будуть класифіковані заново.`);
      }
    } catch (err) {
      console.warn(`Не вдалося прочитати попередній ${config.CLASSIFICATION_OUTPUT_PATH}: ${err.message} — класифікую всі картки заново.`);
    }
  }

  const client = new Anthropic();
  const results = [];

  for (let i = 0; i < dialogs.length; i++) {
    const dialog = dialogs[i];
    const resumed = dialog.leadId ? resumedById.get(dialog.leadId) : null;
    if (resumed) {
      console.log(`\n[${i + 1}/${dialogs.length}] ${dialog.customerName || '(без імені)'} (leadId: ${dialog.leadId}) — вже класифіковано раніше, пропускаю.`);
      // cardIndex у зафіксованому записі оновлюємо на поточну позицію —
      // сам запис (leadId, reason, confidence) лишається тим самим.
      results.push({ ...resumed, cardIndex: dialog.cardIndex });
      continue;
    }
    console.log(`\n[${i + 1}/${dialogs.length}] Класифікую діалог: ${dialog.customerName || '(без імені)'} (leadId: ${dialog.leadId ?? '(немає)'})...`);
    try {
      const classification = await classifyDialog(client, dialog);
      console.log(`  Причина: ${classification.reason} (${classification.confidence})`);
      results.push({
        cardIndex: dialog.cardIndex,
        leadId: dialog.leadId,
        customerName: dialog.customerName,
        reason: classification.reason,
        confidence: classification.confidence,
        rationale: classification.rationale,
      });
    } catch (err) {
      if (isCreditExhaustedError(err)) {
        // Вичерпання кредитів вплине однаково на КОЖНУ наступну картку —
        // немає сенсу мовчки перебирати весь список, записуючи null для
        // кожної (як робить generic-гілка нижче). Зупиняємось одразу,
        // зберігаючи вже готові результати: наступний прогін підхопить їх
        // із resume-кешу за leadId (див. вище) і не витратить кредити повторно.
        fs.writeFileSync(config.CLASSIFICATION_OUTPUT_PATH, JSON.stringify(results, null, 2), 'utf-8');
        console.error(`  ЗАКІНЧИЛИСЬ КРЕДИТИ ANTHROPIC: ${err.message}`);
        await notify(
          `🔴 ЗАКІНЧИЛИСЬ КРЕДИТИ ANTHROPIC, поповни баланс на https://platform.claude.com/settings/billing\n` +
          `classify-leads.js зупинено на картці ${i + 1}/${dialogs.length} (${dialog.customerName || '(без імені)'}).\n` +
          `Успішно класифіковано до зупинки: ${results.length}. Прогрес збережено — наступний запуск продовжить з цього місця.`
        );
        process.exit(1);
      }
      console.error(`  Помилка класифікації: ${err.message}`);
      results.push({
        cardIndex: dialog.cardIndex,
        leadId: dialog.leadId,
        customerName: dialog.customerName,
        reason: null,
        confidence: null,
        rationale: `ПОМИЛКА: ${err.message}`,
      });
    }
  }

  console.log('\n\n=== Результати класифікації ===\n');
  console.table(
    results.map((r) => ({
      'Клієнт': r.customerName || '(без імені)',
      'Причина': r.reason || '(помилка)',
      'Впевненість': r.confidence || '-',
      'Обґрунтування': r.rationale,
    }))
  );

  fs.writeFileSync(config.CLASSIFICATION_OUTPUT_PATH, JSON.stringify(results, null, 2), 'utf-8');
  console.log(`\nЗбережено у: ${config.CLASSIFICATION_OUTPUT_PATH}`);
}

main().catch(async (err) => {
  console.error(err);
  const prefix = isCreditExhaustedError(err)
    ? '🔴 ЗАКІНЧИЛИСЬ КРЕДИТИ ANTHROPIC, поповни баланс на https://platform.claude.com/settings/billing\n'
    : '🔴 КРИТИЧНА ПОМИЛКА в classify-leads.js: ';
  await notify(`${prefix}${err.message}`);
  process.exit(1);
});
