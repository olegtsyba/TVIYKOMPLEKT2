#!/bin/bash
# Автозапуск add-cards-from-chats.js раз на добу вранці (нічний добір): шукає у розділі "Чати"
# клієнток, які повернулись після паузи з конкретним інтересом до товару
# (розмірна сітка / кольори / фото товару / ціна / намір замовити) і не мають
# картки в жодній воронці, і створює їм картку у "Продажі"/"Новий лід".
#
# ПРИЗНАЧЕННЯ ЦЬОГО ВАРІАНТУ: закрити нічний пробіл. Основний розклад
# 9-23/2 з вікном 2h не покриває проміжок 23:00-09:00 — активність за ніч не
# потрапила б у жоден запуск. Тому о 9:05 йде один запуск із вікном 12h
# (дістає приблизно до 21:05 попереднього дня, з запасом перекриваючи
# останній вечірній запуск о 23:25).
#
# Ширше вікно майже нічого не коштує: журнал output/chat-leads-processed.jsonl
# відсіює чати з незмінним updated_at ЩЕ ДО читання історії, тому повторно
# опрацьовуються лише ті, де справді була нова активність.
#
# --limit=20 (більше за денні 10), бо за ніч може накопичитись більше.
#
# LIVE-РЕЖИМ УВІМКНЕНО ТУТ, І ЦЕ СВІДОМЕ ВІДХИЛЕННЯ ВІД КОНВЕНЦІЇ РЕПО.
# Решта wrapper'ів (run-move-to-reminder.sh, run-move-to-manual-review.sh)
# навмисно не вмикають LIVE, а покладаються на змінну в .env. Тут прапор
# стоїть прямо в команді, бо змінна ADD_CARDS_FROM_CHATS_LIVE у .env зробила б
# LIVE також і для РУЧНИХ запусків — а ручний запуск має лишатись безпечним
# dry-run'ом за замовчуванням. Так рішення "cron пише в CRM" лишається
# видимим у git, а не захованим у гітігнореному .env.
# Власник схвалив постійний LIVE 2026-09-13, після того як Крістіна вручну
# звірила перші 4 картки (leads 40163-40166), створені цим скриптом.
#
# Захист від дублювання — журнал опрацьованих (перевірено: повторний запуск
# дає 0 класифікацій) плюс сам критерій відбору: чат із уже створеною карткою
# наступного разу відсіюється ще на кроці 2, бо його contact_id з'являється
# на дошці воронки.
set -uo pipefail
cd "$(dirname "$0")" || exit 1

TS=$(date +%Y-%m-%d-%H)
LOG="output/cron-add-cards-from-chats-morning-${TS}.log"
mkdir -p output

{
  echo "=== Автозапуск add-cards-from-chats.js: $(date -Iseconds) ==="
  node add-cards-from-chats.js --live --window=12h --limit=20
  STATUS=$?
  if [ "$STATUS" -ne 0 ]; then
    echo "ПОМИЛКА: add-cards-from-chats.js завершився з кодом $STATUS"
    node notify-failure.js "⚠️ add-cards-from-chats.js: запуск ПРОВАЛИВСЯ (код $STATUS). Лог: cron-add-cards-from-chats-morning-${TS}.log"
  fi
  echo "=== Завершено: $(date -Iseconds), exit code: $STATUS ==="
  exit "$STATUS"
} >> "$LOG" 2>&1
